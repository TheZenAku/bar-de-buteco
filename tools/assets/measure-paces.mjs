// Writes apps/web/src/engine/clip-paces.ts: how fast each skin's in-place locomotion clips carry a foot on the floor backwards, read from its animation
// bank. npm run assets:paces (after convert-animations.mjs)
//
// The browser plays a step clip at body speed / pace, so the foot on the floor stays put instead of sliding. The retargeted skins step shorter or
// longer than the Mixamo source (Rafael's walk is 1.03 m/s, Nathan's 1.21), so one number for all of them slid.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {readBank} from './measure-punches.mjs';

const root=fileURLToPath(new URL('../../',import.meta.url));
const BANKS=process.env.BAR_ANIMATION_OUTPUT??path.join(root,'apps/web/public/animations');
const OUTPUT=path.join(root,'apps/web/src/engine/clip-paces.ts');
/** The step clips BarScene plays at the body's speed. */
export const PACED=['Walk','Jog','Run','DrunkWalk','FightBack','FightLeft','FightRight'];
const FRAME_MS=1000/60;

/** The median speed of a foot while it is on the floor (within 2 cm of its lowest), both feet, over the whole clip (m/s at 1x). */
export function measurePaces(bytes){
  const bank=readBank(bytes),paces={};
  for(const clip of PACED){
    if(!bank.clips.has(clip))continue;
    const ms=bank.clips.get(clip).duration*1000,speeds=[];
    for(const foot of ['foot_l','foot_r']){
      const way=[];for(let t=0;t<ms;t+=FRAME_MS)way.push(bank.at(clip,foot,t));
      const floor=Math.min(...way.map(p=>p[1]));
      for(let i=1;i<way.length;i++)if(way[i][1]<floor+.02&&way[i-1][1]<floor+.02)speeds.push(Math.hypot(way[i][0]-way[i-1][0],way[i][2]-way[i-1][2])*1000/FRAME_MS);
    }
    speeds.sort((a,b)=>a-b);
    if(speeds.length)paces[clip]=+speeds[Math.floor(speeds.length/2)].toFixed(3);
  }
  return paces;
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const skins={};
  for(const file of fs.readdirSync(BANKS).filter(file=>file.endsWith('.glb')&&!file.endsWith('-dances.glb')).sort()){
    const paces=measurePaces(fs.readFileSync(path.join(BANKS,file)));
    if(Object.keys(paces).length)skins[file.slice(0,-4)]=paces;
  }
  fs.writeFileSync(OUTPUT,`// Generated by tools/assets/measure-paces.mjs (npm run assets:paces) from each skin's animation bank. Do not edit by hand.
/** How fast the body must go (m/s) for a foot on the floor to stay put, for each skin's in-place step clips played at 1x. */
export const CLIP_PACES:Readonly<Record<string,Readonly<Record<string,number>>>>={
${Object.entries(skins).map(([id,paces])=>`  '${id}':{${Object.entries(paces).map(([clip,pace])=>`${clip}:${pace}`).join(',')}},`).join('\n')}
};
`);
  console.log(`${path.relative(root,OUTPUT)}: ${Object.keys(skins).join(', ')}`);
}
