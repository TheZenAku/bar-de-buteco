// Writes packages/shared/src/weapons/bodies-data.ts: each skin standing (the first frame of its Idle), as the bullets see it, read from its
// animation bank: heights above the feet of the hip joint, the chest (spine_03), the neck, the head joint, the top of the head (head_end), the
// right shoulder (upperarm_r), and how far apart the shoulders are (upperarm_l to upperarm_r). See packages/shared/src/weapons/bodies.ts.
// npm run assets:gun-bodies. Run it again when a skin is added or its Idle changes; writing the file restarts the world (it is in shared).
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {readBank} from './measure-punches.mjs';

const root=fileURLToPath(new URL('../../',import.meta.url));
const BANKS=path.join(root,'apps/web/public/animations');
const OUTPUT=path.join(root,'packages/shared/src/weapons/bodies-data.ts');
const round=v=>+v.toFixed(3);

const bodies={};
for(const file of fs.readdirSync(BANKS).filter(file=>file.endsWith('.glb')&&!file.endsWith('-dances.glb')).sort()){
  const id=file.slice(0,-4),bank=readBank(fs.readFileSync(path.join(BANKS,file)));
  if(!bank.clips.has('Idle')){console.log(`${id}: sem Idle, fica de fora`);continue;}
  const at=bone=>bank.at('Idle',bone,0);
  let top;try{top=at('head_end')[1];}catch{top=undefined;}
  const head=at('head')[1];
  // A rig without head_end: the top of the head is about a head's height (23 cm) over the head joint.
  top??=head+.23;
  // A head_end set inside the skull (Leandro's sits 12 cm over the head joint; every other rig 19-28 cm): the top is at least 19 cm up.
  if(top-head<.19){console.log(`${id}: head_end só ${((top-head)*100).toFixed(0)} cm acima da cabeça, usando 19 cm`);top=head+.19;}
  const left=at('upperarm_l'),right=at('upperarm_r');
  bodies[id]={hip:round(at('hip')[1]),chest:round(at('spine_03')[1]),neck:round(at('neck')[1]),head:round(head),top:round(top),shoulder:round(right[1]),
    shoulderWidth:round(Math.hypot(left[0]-right[0],left[1]-right[1],left[2]-right[2]))};
}
const text=`// Generated by tools/assets/measure-gun-bodies.mjs (npm run assets:gun-bodies) from each skin's animation bank. Do not edit by hand.
import type {GunBody} from './bodies.js';

/** Each skin standing in Idle: see GunBody. */
export const GUN_BODY_TABLE:Readonly<Record<string,GunBody>>={
${Object.entries(bodies).map(([id,b])=>`  '${id}':{${Object.entries(b).map(([k,v])=>`${k}:${v}`).join(',')}},`).join('\n')}
};
`;
if(process.argv.includes('--dry'))console.log(text);
else{fs.writeFileSync(OUTPUT,text);console.log(`${path.relative(root,OUTPUT)}: ${Object.keys(bodies).length} skins`);}
console.table(bodies);
